  <h1>Piazza Pulita in cinque minuti</h1>

  <p>È la versione persistente e multigiocatore di <em>Drug Wars</em>, il gioco che
     John E. Dell scrisse nel 1984 come esercizio scolastico di simulazione economica.
     L'originale durava trenta giorni e si giocava da soli. Questo no: il mondo non
     riparte mai, e dentro ci sono tutti gli altri.</p>

  <h2>Il ciclo</h2>
  <p>Vai in una piazza, leggi il listino, compri quello che li' costa poco, ti sposti,
     vendi dove vale di più. Ogni spostamento costa tempo reale — minuti dentro una
     città, ore fra una città e l'altra — e il tempo è la risorsa che non torna.</p>

  <h2>Quello che cambia rispetto all'originale</h2>
  <ul>
    <li><strong>Il mercato è condiviso.</strong> Nel gioco del 1984 il prezzo era
        un'estrazione casuale; qui ogni piazza ha una giacenza e una capacità di
        assorbimento vere. Se compri, il prezzo sale. Se vendi, scende. Se vendi
        troppo, crolla — per tutti, e per ore.</li>
    <li><strong>Il mondo ha un reddito massimo per ora.</strong> Conseguenza diretta
        del punto sopra: la ricchezza non è una fontana, è una torta finita. Si
        cresce togliendo a qualcuno, o allargando la torta.</li>
    <li><strong>Il rischio è una conseguenza.</strong> Il calore sale con il valore
        di quello che muovi, si vede sempre, e quando supera una certa soglia in
        questura si apre un fascicolo — che matura nel tempo, lascia segnali, e si
        può combattere.</li>
    <li><strong>Il contante non basta.</strong> I soldi che fai sono sporchi: ingombrano,
        si perdono nei sequestri e non comprano niente di legale finché non passano
        da un canale di riciclaggio, che si prende la sua percentuale e ha una
        capacità oraria.</li>
  </ul>

  <h2>Gli altri giocatori</h2>
  <p>Si compete soprattutto sul mercato: chi arriva primo al carico appena sbarcato,
     chi fa crollare il prezzo dove tu devi vendere, chi ti brucia una piazza di calore.
     Ma si può anche colpire direttamente — e chi lo fa paga il conto più caro del
     gioco: il profilo criminale non scende con il tempo, e la legge non dimentica.</p>
  <p>Chi vince si prende <strong>solo quello che l'altro aveva addosso</strong>: contanti
     e merce. Il denaro pulito è intestato, i canali e gli immobili pure, e nessuno può
     portarteli via. E sotto mezzo milione <strong>non c'è niente da prendere</strong>:
     pestare un principiante è possibile, non rende una lira, e il calore lo paghi
     lo stesso. Restano la soffiata anonima, la spia da infiltrare in casa d'altri e il
     carico da fermare per strada.</p>
  <p>In gruppo si fanno le <strong>batterie</strong>, che hanno una cassa comune e possono
     tenere una piazza. Il territorio non si conquista dichiarandolo: si tiene
     <em>lavorandoci</em>, e se lo si lascia decade in tre giorni. Chi comanda una piazza
     incassa una quota su quello che ci trattano gli estranei.</p>

  <h2>A che punto è la costruzione</h2>
  <p>Il gioco si costruisce a fasi. Oggi c'è tutto il giro: il mondo, il mercato
     condiviso, il denaro sporco e pulito, la legge, il personaggio con i suoi uomini e
     la rivalità fra giocatori. Manca la rifinitura — obiettivi, classifiche, albo
     d'oro — e il bilanciamento, che si fa con i giocatori veri e non alla scrivania.</p>
