  <h2>Una precisazione</h2>
  <p>È finzione, e il soggetto è quello che è. Le merci del gioco sono numeri con un
     prezzo, una massa e un rischio: non c'è niente, qui dentro, che riguardi il mondo
     reale più di quanto lo riguardi un tabellone del Monopoli.</p>

